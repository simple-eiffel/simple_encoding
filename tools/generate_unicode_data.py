"""Generate SIMPLE_UNICODE_DATA and the normalization test cases from the Unicode Character Database.

Usage: python tools/generate_unicode_data.py <ucd folder>

The folder holds UnicodeData.txt, DerivedNormalizationProps.txt and NormalizationTest.txt for one
Unicode version (https://www.unicode.org/Public/<version>/ucd/). Writes, relative to the repository:
  src/unicode/simple_unicode_data.e            the tables SIMPLE_UNICODE decodes once
  testing/unicode_normalization_cases.e        conformance cases from NormalizationTest.txt

A build tool only: the library itself is pure Eiffel and reads no file at run time.
"""
import os
import sys

VERSION = '15.1.0'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def hx(n):
    return '%x' % n


def wrap(tokens, width=110):
    lines, line = [], ''
    for t in tokens:
        if line and len(line) + 1 + len(t) > width:
            lines.append(line)
            line = t
        else:
            line = t if not line else line + ' ' + t
    if line:
        lines.append(line)
    return lines


LIMIT = 30000
    # The compiler refuses a manifest string over 32,767 characters, so a table is written in parts.


def verbatim(name, comment, tokens):
    parts, part, size = [], [], 0
    for line in wrap(tokens):
        if part and size + len(line) + 1 > LIMIT:
            parts.append(part)
            part, size = [], 0
        part.append(line)
        size += len(line) + 1
    parts.append(part)
    text = '\t%s: STRING_8\n\t\t\t-- %s\n\t\tonce\n\t\t\tcreate Result.make (%d)\n' % (name, comment, sum(len(t) + 1 for t in tokens))
    for n in range(len(parts)):
        text += '\t\t\tResult.append (%s_part_%d)\n\t\t\tResult.append_character (\'%%N\')\n' % (name.capitalize(), n + 1)
    text += '\t\tend\n\n'
    for n, lines in enumerate(parts):
        text += '\t%s_part_%d: STRING_8 = "[\n%s\n]"\n\n' % (name.capitalize(), n + 1, '\n'.join(lines))
    return text


def read_unicode_data(path):
    entries = {}
    first = None
    for line in open(path, encoding='utf-8'):
        f = line.rstrip('\n').split(';')
        cp = int(f[0], 16)
        if f[1].endswith(', First>'):
            first = cp
            continue
        if f[1].endswith(', Last>'):
            for c in range(first, cp + 1):
                entries[c] = (f[2], int(f[3]), '', '', '')
            first = None
            continue
        entries[cp] = (f[2], int(f[3]), f[5], f[12], f[13])
    return entries


def read_exclusions(path):
    result = []
    for line in open(path, encoding='utf-8'):
        line = line.split('#')[0].strip()
        if not line:
            continue
        rng, prop = [x.strip() for x in line.split(';')[:2]]
        if prop != 'Full_Composition_Exclusion':
            continue
        if '..' in rng:
            a, b = [int(x, 16) for x in rng.split('..')]
        else:
            a = b = int(rng, 16)
        result.append((a, b))
    return result


def main():
    ucd = sys.argv[1]
    data = read_unicode_data(os.path.join(ucd, 'UnicodeData.txt'))
    exclusions = read_exclusions(os.path.join(ucd, 'DerivedNormalizationProps.txt'))

    categories, previous = [], None
    for cp in range(0x110000):
        cat = data[cp][0] if cp in data else 'Cn'
        if cat != previous:
            categories.append(hx(cp) + cat)
            previous = cat

    classes, cp = [], 0
    while cp < 0x110000:
        ccc = data[cp][1] if cp in data else 0
        if ccc:
            end = cp
            while end + 1 < 0x110000 and (data[end + 1][1] if end + 1 in data else 0) == ccc:
                end += 1
            classes.append((hx(cp) if end == cp else hx(cp) + '-' + hx(end)) + ':' + str(ccc))
            cp = end + 1
        else:
            cp += 1

    decompositions, lowers, uppers = [], [], []
    for cp in sorted(data):
        _, _, dec, upper, lower = data[cp]
        if dec:
            parts = dec.split()
            if parts[0].startswith('<'):
                decompositions.append('~' + hx(cp) + ':' + '.'.join(hx(int(p, 16)) for p in parts[1:]))
            else:
                decompositions.append(hx(cp) + ':' + '.'.join(hx(int(p, 16)) for p in parts))
        if lower:
            lowers.append(hx(cp) + ':' + hx(int(lower, 16)))
        if upper:
            uppers.append(hx(cp) + ':' + hx(int(upper, 16)))

    excluded = [hx(a) if a == b else hx(a) + '-' + hx(b) for a, b in exclusions]

    out = ['note\n',
           '\tdescription: "[\n',
           '\t\tUnicode %s character data for SIMPLE_UNICODE: general category runs,\n' % VERSION,
           '\t\tcanonical combining classes, decompositions (~ marks a compatibility one),\n',
           '\t\tsimple case mappings and the full composition exclusions. Numbers are lowercase\n',
           '\t\thexadecimal. GENERATED by tools/generate_unicode_data.py from the Unicode\n',
           '\t\tCharacter Database: do not edit by hand; regenerate.\n',
           '\t]"\n',
           '\tlicense: "Unicode data: Unicode License v3 (https://www.unicode.org/license.txt)"\n\n',
           'class\n\tSIMPLE_UNICODE_DATA\n\n',
           'feature -- Access\n\n',
           '\tUnicode_version: STRING_8 = "%s"\n\t\t\t-- The Unicode version of these tables.\n\n' % VERSION,
           verbatim('category_runs', 'Each run start and its general category, every code point covered.', categories),
           verbatim('combining_class_runs', 'Code points (or ranges) with a nonzero canonical combining class.', classes),
           verbatim('decomposition_list', 'Canonical decompositions; ~ before a compatibility one. Hangul is algorithmic.', decompositions),
           verbatim('lower_mappings', 'Simple lowercase mappings.', lowers),
           verbatim('upper_mappings', 'Simple uppercase mappings.', uppers),
           verbatim('composition_exclusions', 'Full_Composition_Exclusion code points (or ranges).', excluded),
           'end\n']
    write(os.path.join(ROOT, 'src', 'unicode', 'simple_unicode_data.e'), ''.join(out))

    cases, part = [], ''
    for i, line in enumerate(open(os.path.join(ucd, 'NormalizationTest.txt'), encoding='utf-8')):
        if line.startswith('@'):
            part = line.split()[0]
            continue
        line = line.split('#')[0].strip()
        if not line:
            continue
        if part == '@Part1' and i % 20 != 0:
            continue
        columns = line.split(';')[:5]
        cases.append(';'.join('.'.join(hx(int(c, 16)) for c in col.split()) for col in columns))
    chunks = [cases[k:k + 250] for k in range(0, len(cases), 250)]
    t = ['note\n',
         '\tdescription: "[\n',
         '\t\tConformance cases from NormalizationTest.txt (Unicode %s): every case of\n' % VERSION,
         '\t\tparts 0, 2 and 3 and every twentieth line of part 1. Columns c1;c2;c3;c4;c5,\n',
         '\t\tcode points in lowercase hexadecimal joined by dots. GENERATED by\n',
         '\t\ttools/generate_unicode_data.py: do not edit by hand.\n',
         '\t]"\n\n',
         'class\n\tUNICODE_NORMALIZATION_CASES\n\n',
         'feature -- Access\n\n',
         '\tcase_count: INTEGER = %d\n\t\t\t-- How many cases `case_lines\' gives.\n\n' % len(cases),
         '\tcase_lines: ARRAYED_LIST [STRING_8]\n',
         '\t\t\t-- One case per line.\n',
         '\t\tdo\n',
         '\t\t\tcreate Result.make (case_count)\n']
    for n in range(len(chunks)):
        t.append('\t\t\tResult.append (Chunk_%d.split (\'%%N\'))\n' % (n + 1))
    t.append('\t\tend\n\n')
    t.append('feature {NONE} -- Cases\n\n')
    for n, chunk in enumerate(chunks):
        t.append('\tChunk_%d: STRING_8 = "[\n%s\n]"\n\n' % (n + 1, '\n'.join(chunk)))
    t.append('end\n')
    write(os.path.join(ROOT, 'testing', 'unicode_normalization_cases.e'), ''.join(t))
    print('categories %d runs, classes %d, decompositions %d, lower %d, upper %d, exclusions %d, cases %d'
          % (len(categories), len(classes), len(decompositions), len(lowers), len(uppers), len(excluded), len(cases)))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(text.replace('\n', '\r\n').encode('ascii'))


if __name__ == '__main__':
    main()
